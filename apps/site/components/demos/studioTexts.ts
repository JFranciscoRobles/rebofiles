/** How long ago, in the language: “3 days ago”, “hace 3 días”, “3天前”. */
export function agoIn(language: StudioLanguage, iso: string) {
  const minutes = Math.round((Date.now() - new Date(iso).getTime()) / 60000);
  const say = new Intl.RelativeTimeFormat(language, { numeric: 'auto' });
  if (minutes < 60) return say.format(-minutes, 'minute');
  if (minutes < 60 * 24) return say.format(-Math.round(minutes / 60), 'hour');
  return say.format(-Math.round(minutes / 60 / 24), 'day');
}
