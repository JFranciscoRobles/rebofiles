const WORDS: Partial<Record<Locale, Words>> = { es, zh };

/** The reference in a language: the same rows, with what each does said in it where it is written. */
export function referenceIn(locale: Locale) {
  const w = WORDS[locale];
  return {
    PROPS: PROPS.map((prop) => ({ ...prop, does: w?.props[prop.name] ?? prop.does })),
    HOOKS: HOOKS.map((hook) => ({ ...hook, short: w?.hooks[hook.name]?.[0] ?? hook.short, gives: w?.hooks[hook.name]?.[1] ?? hook.gives })),
    CLIENT: CLIENT.map((method) => ({ ...method, does: w?.client[method.name] ?? method.does })),
    SERVER_OPTIONS: SERVER_OPTIONS.map((option) => ({ ...option, does: w?.server[option.name] ?? option.does })),
    PACKAGE_DOCS: PACKAGE_DOCS.map((pkg) => ({ ...pkg, what: w?.packages[pkg.name]?.[0] ?? pkg.what, runs: w?.packages[pkg.name]?.[1] ?? pkg.runs })),
  };
}
